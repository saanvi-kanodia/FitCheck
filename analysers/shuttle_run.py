import cv2
import mediapipe as mp
from core.pose import Tracker
import numpy as np
import argparse
import time
import os
from scipy.stats import linregress

def parse_args():
    parser = argparse.ArgumentParser(
        description='Shuttle Run Analysis.')
    parser.add_argument('-v', '--video', type=str, default='shuttlerun1.mp4', help='Input video file')
    parser.add_argument('-o', '--output', type=str, default=None, help='Output analyzed video file')
    parser.add_argument('--det', type=float, default=0.5, help='Detection confidence')
    parser.add_argument('--track', type=float, default=0.5, help='Tracking confidence')
    parser.add_argument('-c', '--complexity', type=int, default=0, help='Model complexity (0, 1, 2)')
    return parser.parse_args()

def calculate_speed(start_time, end_time, distance):
    return distance / (end_time - start_time) if end_time > start_time else 0

def analyze_speed_trend(speeds):
    if len(speeds) < 2:
        return "Not enough data to analyze trend"

    x = np.arange(len(speeds))
    slope, _, _, _, _ = linregress(x, speeds)

    if isinstance(slope, (int, float)):
        if slope > 0.0:
            return "Increasing"
        elif slope < 0.0:
            return "Decreasing"
        else:
            return "Consistent"
    return "Invalid slope value"

def generate_analytics_report(analytics, video_filename, output_video=None):
    session_duration = analytics['duration']
    average_speed = np.mean(analytics['speeds']) if analytics['speeds'] else 0
    consistency = np.std(analytics['speeds']) if analytics['speeds'] else 0
    speed_trend = analyze_speed_trend(analytics['speeds'])

    # Calculate scores
    performance_score = min(average_speed / 5.0 * 10, 10) if average_speed > 0 else 0  # Assuming 5 m/s is excellent
    form_score = max(0, 4 - len(analytics.get('cheats', [])))  # Form score out of 4, deduct for each cheat

    report = f"""

Exercise: shuttle_run
Value: {average_speed:.2f} 
Form_Score: {form_score:.1f}
Max_Form_Score: 4

================================================================================
Session Date: {time.strftime('%Y-%m-%d %H:%M:%S')}
Original Video: {video_filename}
Analyzed Video: {output_video if output_video else 'Not saved'}
Session Duration: {session_duration:.1f} seconds

PERFORMANCE SUMMARY:
================================================================================
🏃 Average Speed: {average_speed:.2f} m/s
📊 Consistency (Speed Std Dev): {consistency:.2f}
📈 Speed Trend: {speed_trend}
Total Runs: {analytics['run_count']}
Legs Covered: {analytics['legs']}
⭐ Form Score: {form_score:.1f}/4.0

CHEATS DETECTED:
================================================================================
"""
    for cheat in analytics.get('cheats', []):
        report += f"- {cheat}\n"

    report += f"""
================================================================================
Report generated by Fitness Tracking App v2.0
================================================================================
"""

    timestamp = time.strftime('%Y%m%d_%H%M%S')
    downloads_dir = os.path.expanduser('~/Downloads')
    os.makedirs(downloads_dir, exist_ok=True)
    report_filename = os.path.join(downloads_dir, f"shuttlerun_report_{timestamp}.txt")
    with open(report_filename, 'w') as f:
        f.write(report)

    print(f"\n📊 ANALYTICS REPORT SAVED: {report_filename}")
    return report_filename

TURN_GAP = 0.25     # reversal (fraction of frame width) needed to confirm a turn
MIN_LEG = 0.4       # a leg must cover at least this much of the frame
LEG_METRES = 10     # assumed distance between the two markers


def main():
    args = parse_args()
    mp_pose = mp.solutions.pose
    vid = cv2.VideoCapture(args.video)
    width = int(vid.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(vid.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = vid.get(cv2.CAP_PROP_FPS) or 30

    if args.output is None:
        timestamp = time.strftime('%Y%m%d_%H%M%S')
        input_name = args.video.split('.')[0] if args.video else 'shuttlerun'
        os.makedirs("analysed", exist_ok=True)
        args.output = f"analysed/{input_name}analyzed{timestamp}.mp4"
    print(f"📹 Saving analyzed video as: {args.output}")

    out = cv2.VideoWriter(args.output, cv2.VideoWriter_fourcc(*'mp4v'), fps, (width, height))
    pose = Tracker(video=args.video, static_image_mode=False, model_complexity=args.complexity,
                        min_detection_confidence=args.det, min_tracking_confidence=args.track)

    analytics = {'speeds': [], 'run_count': 0, 'legs': 0, 'duration': 0.0, 'cheats': []}
    # Turn detection: follow the furthest point reached in the current direction;
    # once the runner comes back from it by TURN_GAP, that point was a turn.
    last_turn = None          # (time, x) of the previous turn
    extreme = None            # (time, x) furthest point since the last turn
    direction = 0             # +1 moving right, -1 moving left, 0 unknown
    history = []              # (time, x) for pause detection
    pauses = []
    lap_text, frame_no = "", 0
    spans = []                # distance covered by each completed leg
    leg_done = False          # current leg already counted on reaching the far end

    def finish_leg(turn):
        nonlocal lap_text, leg_done
        if leg_done:
            # Leg was counted early at the far end; now time it to the actual turn.
            leg_done = False
            if turn[0] > last_turn[0]:
                analytics['speeds'][-1] = LEG_METRES / (turn[0] - last_turn[0])
            return
        if last_turn and abs(turn[1] - last_turn[1]) >= MIN_LEG and turn[0] > last_turn[0]:
            spans.append(abs(turn[1] - last_turn[1]))
            speed = LEG_METRES / (turn[0] - last_turn[0])
            analytics['speeds'].append(speed)
            analytics['legs'] += 1
            analytics['run_count'] = analytics['legs'] // 2
            lap_text = f"Leg {analytics['legs']}: {speed:.2f} m/s"

    while vid.isOpened():
        ret, frame = vid.read()
        if not ret:
            break
        t = frame_no / fps
        frame_no += 1
        results = pose.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))

        if results.pose_landmarks:
            lm = results.pose_landmarks.landmark
            x = (lm[mp_pose.PoseLandmark.LEFT_HIP.value].x + lm[mp_pose.PoseLandmark.RIGHT_HIP.value].x) / 2

            if extreme is None:
                extreme = last_turn = (t, x)
            elif direction >= 0 and x >= extreme[1] or direction <= 0 and x <= extreme[1]:
                if direction == 0 and abs(x - last_turn[1]) > 0.05:
                    direction = 1 if x > last_turn[1] else -1
                extreme = (t, x) if direction else extreme
            elif abs(x - extreme[1]) >= TURN_GAP:
                finish_leg(extreme)
                last_turn, direction = extreme, -direction if direction else (1 if x > extreme[1] else -1)
                extreme = (t, x)

            # Count the leg as soon as the runner reaches the far end, so the overlay
            # updates live (the last leg has no turn after it).
            if spans and not leg_done and direction and abs(x - last_turn[1]) >= 0.9 * (sum(spans) / len(spans)):
                finish_leg((t, x))
                leg_done = True

            # Pause: barely moving for a full second in the middle of the course
            history.append((t, x))
            history = [h for h in history if t - h[0] <= 1.0]
            if t - history[0][0] >= 0.95 and 0.3 < x < 0.7 and max(h[1] for h in history) - min(h[1] for h in history) < 0.03:
                if not pauses or t - pauses[-1] > 2:
                    pauses.append(t)
                    cv2.putText(frame, "Pause", (10, 150), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 0, 255), 2)

            cv2.putText(frame, f"Runs: {analytics['run_count']}  Legs: {analytics['legs']}", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 0, 0), 2)
            if lap_text:
                cv2.putText(frame, lap_text, (10, 70), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 255), 2)

        out.write(frame)
        cv2.imshow('Shuttle Run Analysis', frame)
        if cv2.waitKey(10) & 0xFF == ord('q'):
            break

    # The last leg ends at the end of the video rather than at a turn.
    if extreme:
        finish_leg(extreme)
    analytics['duration'] = frame_no / fps
    analytics['cheats'] = [f"{p:.1f}s: Excessive pause" for p in pauses]

    vid.release()
    out.release()
    cv2.destroyAllWindows()

    print(f"Total Runs: {analytics['run_count']} ({analytics['legs']} legs)")
    generate_analytics_report(analytics, args.video, args.output)


if __name__ == "__main__":
    main()
