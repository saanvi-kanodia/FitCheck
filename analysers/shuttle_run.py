import cv2
import mediapipe as mp
import numpy as np
import argparse
import time
import os
from scipy.stats import linregress

def parse_args():
    parser = argparse.ArgumentParser(
        description='Shuttle Run Analysis.')
    parser.add_argument('-v', '--video', type=str, default='shuttlerun1.mp4', help='Input video file')
    parser.add_argument('-o', '--output', type=str, default=None, help='Output analyzed video file')
    parser.add_argument('--det', type=float, default=0.5, help='Detection confidence')
    parser.add_argument('--track', type=float, default=0.5, help='Tracking confidence')
    parser.add_argument('-c', '--complexity', type=int, default=0, help='Model complexity (0, 1, 2)')
    return parser.parse_args()

def calculate_speed(start_time, end_time, distance):
    return distance / (end_time - start_time) if end_time > start_time else 0

def analyze_speed_trend(speeds):
    if len(speeds) < 2:
        return "Not enough data to analyze trend"

    x = np.arange(len(speeds))
    slope, _, _, _, _ = linregress(x, speeds)

    if isinstance(slope, (int, float)):
        if slope > 0.0:
            return "Increasing"
        elif slope < 0.0:
            return "Decreasing"
        else:
            return "Consistent"
    return "Invalid slope value"

def generate_analytics_report(analytics, video_filename, output_video=None):
    session_duration = time.time() - analytics['session_start_time']
    average_speed = np.mean(analytics['speeds']) if analytics['speeds'] else 0
    consistency = np.std(analytics['speeds']) if analytics['speeds'] else 0
    speed_trend = analyze_speed_trend(analytics['speeds'])

    # Calculate scores
    performance_score = min(average_speed / 5.0 * 10, 10) if average_speed > 0 else 0  # Assuming 5 m/s is excellent
    form_score = max(0, 4 - len(analytics.get('cheats', [])))  # Form score out of 4, deduct for each cheat

    report = f"""

Exercise: shuttle_run
Value: {average_speed:.2f} 
Form_Score: {form_score:.1f}
Max_Form_Score: 4

================================================================================
Session Date: {time.strftime('%Y-%m-%d %H:%M:%S')}
Original Video: {video_filename}
Analyzed Video: {output_video if output_video else 'Not saved'}
Session Duration: {session_duration:.1f} seconds

PERFORMANCE SUMMARY:
================================================================================
🏃 Average Speed: {average_speed:.2f} m/s
📊 Consistency (Speed Std Dev): {consistency:.2f}
📈 Speed Trend: {speed_trend}
Total Runs: {analytics['run_count']}
⭐ Form Score: {form_score:.1f}/4.0

CHEATS DETECTED:
================================================================================
"""
    for cheat in analytics.get('cheats', []):
        report += f"- {cheat}\n"

    report += f"""
================================================================================
Report generated by Fitness Tracking App v2.0
================================================================================
"""

    timestamp = time.strftime('%Y%m%d_%H%M%S')
    downloads_dir = os.path.expanduser('~/Downloads')
    os.makedirs(downloads_dir, exist_ok=True)
    report_filename = os.path.join(downloads_dir, f"shuttlerun_report_{timestamp}.txt")
    with open(report_filename, 'w') as f:
        f.write(report)

    print(f"\n📊 ANALYTICS REPORT SAVED: {report_filename}")
    return report_filename

def detect_cheating(torso_positions, start_pos, end_pos):
    cheats = []

    # Check for skipping cones
    if torso_positions[0] < start_pos or torso_positions[-1] > end_pos:
        cheats.append("Skipped cones")

    # Check for excessive pauses
    for i in range(1, len(torso_positions)):
        if abs(torso_positions[i] - torso_positions[i - 1]) < 0.01:  # Threshold for minimal movement
            cheats.append("Excessive pause detected")
            break

    # Check for wrong direction
    for i in range(1, len(torso_positions)):
        if abs(torso_positions[i] - torso_positions[i - 1]) > 0.5:  # Threshold for deviation
            cheats.append("Wrong direction detected")
            break

    return cheats

def main():
    args = parse_args()

    mp_pose = mp.solutions.pose

    vid = cv2.VideoCapture(args.video)

    width = int(vid.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(vid.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = int(vid.get(cv2.CAP_PROP_FPS))

    if args.output is None:
        timestamp = time.strftime('%Y%m%d_%H%M%S')
        input_name = args.video.split('.')[0] if args.video else 'shuttlerun'
        os.makedirs("analysed", exist_ok=True)
        args.output = f"analysed/{input_name}analyzed{timestamp}.mp4"

    print(f"📹 Saving analyzed video as: {args.output}")

    codec = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(args.output, codec, fps, (width, height))

    pose = mp_pose.Pose(static_image_mode=False, min_detection_confidence=args.det, min_tracking_confidence=args.track)

    session_analytics = {
        'speeds': [],
        'run_count': 0,
        'session_start_time': time.time(),
        'cheats': []
    }

    run_start_time = None
    run_end_time = None
    in_run = False
    torso_positions = []

    while vid.isOpened():
        ret, frame = vid.read()
        if not ret:
            break

        image = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        results = pose.process(image)

        if results.pose_landmarks:
            landmarks = results.pose_landmarks.landmark

            nose = [landmarks[mp_pose.PoseLandmark.NOSE.value].x, landmarks[mp_pose.PoseLandmark.NOSE.value].y]
            torso_x = landmarks[mp_pose.PoseLandmark.NOSE.value].x
            torso_positions.append(torso_x)

            if not in_run and nose[0] < 0.2:  # Threshold to detect run start
                in_run = True
                run_start_time = time.time()

            if in_run and nose[0] > 0.8:  # Threshold to detect run end
                in_run = False
                run_end_time = time.time()
                session_analytics['run_count'] += 1

                speed = calculate_speed(run_start_time, run_end_time, distance=10)  # Assuming 10 meters distance
                session_analytics['speeds'].append(speed)

                cv2.putText(frame, f"Lap Speed: {speed:.2f} m/s", (10, 110), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 255), 2)

            if in_run:
                cv2.putText(frame, "Running...", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 0), 2)

            cv2.putText(frame, f"Run Count: {session_analytics['run_count']}", (10, 70), cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 0, 0), 2)

        out.write(frame)
        cv2.imshow('Shuttle Run Analysis', frame)

        if cv2.waitKey(10) & 0xFF == ord('q'):
            break

    vid.release()
    out.release()
    cv2.destroyAllWindows()

    if run_start_time and run_end_time:
        completion_time = run_end_time - run_start_time
        print(f"Completion Time: {completion_time:.2f} seconds")

        cheats = detect_cheating(torso_positions, start_pos=0.2, end_pos=0.8)
        session_analytics['cheats'] = cheats
        if cheats:
            print("Cheat Detection:")
            for cheat in cheats:
                print(f"- {cheat}")
        else:
            print("No cheating detected.")

    generate_analytics_report(session_analytics, args.video, args.output)

if __name__ == "__main__":
    main()