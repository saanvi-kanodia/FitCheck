def generate_analytics_report(analytics, video_filename, output_video=None):
    session_duration = time.time() - analytics['session_start_time']
    jump_height = analytics['max_jump_height']
    landing_stability = 'Stable' if analytics['stable_landings'] else 'Unstable'
    avg_form_score = np.mean(analytics['form_scores']) if analytics['form_scores'] else 0
    form_consistency = (analytics['good_form_frames'] / len(analytics['form_scores']) * 100) if analytics['form_scores'] else 0

    report = f"""

Exercise: vertical_jump
Value: {jump_height:.2f} 
Form_Score: {avg_form_score:.1f}
Max_Form_Score: 4

================================================================================
Session Date: {time.strftime('%Y-%m-%d %H:%M:%S')}
Original Video: {video_filename}
Analyzed Video: {output_video if output_video else 'Not saved'}
Session Duration: {session_duration:.1f} seconds

PERFORMANCE SUMMARY:
================================================================================
📏 Max Jump Height: {jump_height:.2f} meters
🦵 Landing Stability: {landing_stability}
Total Jumps: {analytics['jump_count']}
⭐ Average Form Score: {avg_form_score:.1f}/4.0

DETAILED ANALYTICS:
================================================================================
🎯 Total Frames Analyzed: {len(analytics['form_scores'])}
✅ Good Form Frames: {analytics['good_form_frames']}
❌ Poor Form Frames: {len(analytics['form_scores']) - analytics['good_form_frames']}

CHEATS DETECTED:
================================================================================
"""
    for cheat in analytics['cheat_events']:
        report += f"- {cheat['time']:.2f}s: {cheat['type']}\n"

    report += f"""
FORM WRONG TIMESTAMPS:
================================================================================
"""
    for t in analytics['form_wrong_times']:
        report += f"- {t:.2f}s\n"

    report += f"""
================================================================================
Report generated by Fitness Tracking App v2.0
================================================================================
"""

    timestamp = time.strftime('%Y%m%d_%H%M%S')
    downloads_dir = os.path.expanduser('~/Downloads')
    os.makedirs(downloads_dir, exist_ok=True)
    report_filename = os.path.join(downloads_dir, f"verticaljump_report_{timestamp}.txt")
    with open(report_filename, 'w') as f:
        f.write(report)

    print(f"\n📊 ANALYTICS REPORT SAVED: {report_filename}")
    return report_filename

def main():
    args = parse_args()

    mp_drawing = mp.solutions.drawing_utils
    mp_pose = mp.solutions.pose

    vid = cv2.VideoCapture(args.video)

    width = int(vid.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(vid.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = int(vid.get(cv2.CAP_PROP_FPS))

    if args.output is None:
        timestamp = time.strftime('%Y%m%d_%H%M%S')
        input_name = args.video.split('.')[0] if args.video else 'verticaljump'
        os.makedirs("analysed", exist_ok=True)
        args.output = f"analysed/{input_name}analyzed{timestamp}.mp4"

    print(f"📹 Saving analyzed video as: {args.output}")

    codec = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(args.output, codec, fps, (width, height))

    pose = mp_pose.Pose(static_image_mode=False, min_detection_confidence=args.det, min_tracking_confidence=args.track)

    initial_time = time.time()
    last_cheat_time = {'knee': 0.0, 'landing': 0.0, 'camera': 0.0}

    session_analytics = {
        'max_jump_height': 0,
        'stable_landings': True,
        'jump_count': 0,
        'session_start_time': time.time(),
        'form_scores': [],
        'good_form_frames': 0,
        'cheat_events': [],
        'form_wrong_times': []
    }

    baseline_hip_y = None
    max_hip_y = float('inf')  # Initialize to a very high value
    in_air = False

    while vid.isOpened():
        ret, frame = vid.read()
        if not ret:
            break

        image = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        results = pose.process(image)

        if results.pose_landmarks:
            landmarks = results.pose_landmarks.landmark

            hip = [landmarks[mp_pose.PoseLandmark.LEFT_HIP.value].x, landmarks[mp_pose.PoseLandmark.LEFT_HIP.value].y]
            knee = [landmarks[mp_pose.PoseLandmark.LEFT_KNEE.value].x, landmarks[mp_pose.PoseLandmark.LEFT_KNEE.value].y]
            ankle = [landmarks[mp_pose.PoseLandmark.LEFT_ANKLE.value].x, landmarks[mp_pose.PoseLandmark.LEFT_ANKLE.value].y]
            shoulder = [landmarks[mp_pose.PoseLandmark.LEFT_SHOULDER.value].x, landmarks[mp_pose.PoseLandmark.LEFT_SHOULDER.value].y]

            # Calculate angles
            knee_angle = calculate_angle(hip, knee, ankle)
            torso_angle = calculate_angle(shoulder, hip, knee)

            # FORM SCORING SYSTEM (out of 4)
            form_score = 4
            if knee_angle > 110:
                form_score -= 1
            if torso_angle > 15:
                form_score -= 1
            if baseline_hip_y and abs(hip[1] - baseline_hip_y) > 0.05 * height:
                form_score -= 1
            # Symmetry not implemented yet

            session_analytics['form_scores'].append(form_score)
            if form_score >= 3:
                session_analytics['good_form_frames'] += 1
            else:
                session_analytics['form_wrong_times'].append(time.time() - initial_time)

            # Cheat detection: Knee not flexed enough
            if knee_angle > 110:
                cv2.putText(frame, "Cheat: Knee not flexed enough", (10, 110), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 0, 255), 2)
                if time.time() - last_cheat_time['knee'] > 1:
                    session_analytics['cheat_events'].append({'time': time.time() - initial_time, 'type': 'Knee not flexed enough'})
                    last_cheat_time['knee'] = time.time()

            # Cheat detection: Not landing properly
            if not in_air and torso_angle > 15:
                cv2.putText(frame, "Cheat: Improper landing", (10, 150), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 0, 255), 2)
                if time.time() - last_cheat_time['landing'] > 1:
                    session_analytics['cheat_events'].append({'time': time.time() - initial_time, 'type': 'Improper landing'})
                    last_cheat_time['landing'] = time.time()
                    session_analytics['stable_landings'] = False

            # Cheat detection: Camera movement affecting hip detection
            if baseline_hip_y and abs(hip[1] - baseline_hip_y) > 0.05 * height:
                cv2.putText(frame, "Cheat: Camera movement detected", (10, 190), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 0, 255), 2)
                if time.time() - last_cheat_time['camera'] > 1:
                    session_analytics['cheat_events'].append({'time': time.time() - initial_time, 'type': 'Camera movement detected'})
                    last_cheat_time['camera'] = time.time()

            if baseline_hip_y is None:
                baseline_hip_y = hip[1]

            if hip[1] < baseline_hip_y - 0.1 and not in_air:  # Threshold to detect jump start
                in_air = True
                session_analytics['jump_count'] += 1
                max_hip_y = hip[1]  # Reset max height for the new jump

            if in_air and hip[1] > baseline_hip_y - 0.05:  # Threshold to detect landing
                in_air = False

            if in_air:
                max_hip_y = min(max_hip_y, hip[1])  # Update max height during the jump

            jump_height = baseline_hip_y - max_hip_y if baseline_hip_y and max_hip_y != float('inf') else 0
            session_analytics['max_jump_height'] = max(session_analytics['max_jump_height'], jump_height)

            cv2.putText(frame, f"Jump Height: {jump_height:.2f} meters", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 0, 0), 2)
            cv2.putText(frame, f"Jump Count: {session_analytics['jump_count']}", (10, 70), cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 0, 0), 2)

        out.write(frame)
        cv2.imshow('Vertical Jump Analysis', frame)

        if cv2.waitKey(10) & 0xFF == ord('q'):
            break

    vid.release()
    out.release()
    cv2.destroyAllWindows()

    generate_analytics_report(session_analytics, args.video, args.output)

if __name__ == "__main__":
    main()